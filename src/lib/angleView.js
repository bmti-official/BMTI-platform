// 화면에 보여 줄 값으로 바꿔 주는 자리.
//
// 목은 담을 때와 보여 줄 때의 기준선이 다르다.
//   담을 때 … 수직선에서 얼마나 기울었나 (0에 가까울수록 곧다)
//   볼 때  … 수평선에서 얼마나 섰나 = CVA (클수록 곧다)
// 두 값은 같은 두 점에서 나오므로 **정확히 90도에서 서로를 뺀 값**이다.
// 그래서 칸을 새로 만들지 않고 읽을 때만 바꾼다 — 예전에 잰 판도 그대로 살아난다.
//
// 왜 바꾸나. 임상에서 거북목을 말할 때 쓰는 잣대가 CVA(귀-C7-수평)라
// 그 관례를 따르면 셋이 모두 '클수록 좋다'로 모인다. 목만 반대로 읽히지 않는다.
//
// **다만 경계값은 우리 것이다.** 임상 기준(50도 미만 경도·30도 미만 심함)은
// 아래 점이 C7일 때의 숫자다. 미디어파이프에는 C7이 없어 어깨점을 대신 쓰므로
// 같은 사람이라도 15~25도쯤 크게 나온다. 임상 숫자를 그대로 가져다 쓰면 안 된다.
const r1 = (v) => Math.round(v * 10) / 10;

export const toCVA = (neckBend) => (neckBend == null || !Number.isFinite(Number(neckBend))
  ? null : r1(90 - Number(neckBend)));

/** 잰 판들을 화면용으로. 목만 CVA로 바꾸고 나머지는 그대로 둔다. */
export const toView = (rows = []) => (rows || []).map((r) => (
  r && r.neck_bend != null ? { ...r, neck_bend: toCVA(r.neck_bend) } : r));
