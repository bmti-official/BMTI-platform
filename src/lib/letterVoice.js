// '와/과' 붙이기
function josaWa(w) {
  const s = String(w || '');
  const c = s.charCodeAt(s.length - 1);
  const has = c >= 0xAC00 && c <= 0xD7A3 && (c - 0xAC00) % 28 !== 0;
  return has ? '과' : '와';
}

// 네 글자 코드에서 말투 갈래(DZ/DM/QZ/QM)를 꺼낸다.
export function toneKey(bmtiCode) {
  const a = String(bmtiCode || '').split('-')[0].toUpperCase();
  const dq = a.includes('Q') ? 'Q' : 'D';
  const zm = a.includes('M') ? 'M' : 'Z';
  return dq + zm;
}
