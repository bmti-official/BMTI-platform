// 파트너의 편지 — 문장 곳간.
//
// 같은 기록이라도 달마다 다른 문장으로 읽히게, 자리마다 문장 후보를 여러 개 두고
// '닉네임 + 그 달'로 정해지는 하나를 고른다. 한 번 정해지면 다시 열어도 같은 편지다.
//
// AI를 그때그때 부르지 않고 미리 써 둔 문장을 고르는 방식이다.
// 요금이 들지 않고, 손님마다 엉뚱한 말이 나갈 걱정도 없다.
//
// 자리마다 여섯 갈래 안팎을 둔다. 셋만 두면 반년이면 같은 편지가 돌아오는데,
// 한 해를 함께 보낸 사람일수록 그 반복을 먼저 알아챈다.

// 닉네임과 달을 섞어 늘 같은 숫자를 얻는다(FNV-1a).
function hash(str) {
  let h = 2166136261;
  const s = String(str || '');
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

// 자리(salt)마다 다른 문장이 뽑히도록 씨앗에 자리 이름을 섞는다.
export function pickBy(seed, salt, list) {
  if (!list || !list.length) return null;
  return list[hash(`${seed}|${salt}`) % list.length];
}

