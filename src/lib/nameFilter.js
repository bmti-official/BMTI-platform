// 붙여서 본다 — 띄어쓰기·기호 빼고, 흔한 숫자 바꿔치기(1→ㅣ 등)는 지운다
const squash = (s) => String(s || '').toLowerCase()
  .replace(/[\s._\-~!@#$%^&*()+=[\]{}|\\/:;"'<>,?`·•ㆍ]/g, '')
  .replace(/[0-9]/g, (d) => (d === '6' || d === '9' ? d : ''));   // '69'는 남긴다

/** 쓸 수 없는 말이 들었으면 그 갈래(예: '욕설'), 괜찮으면 null */
export function badNameReason(name) {
  const raw = String(name || '').toLowerCase().replace(/\s/g, '');
  const flat = squash(name);
  for (const [kind, words] of Object.entries(LISTS)) {
    if (words.some((w) => raw.includes(w) || flat.includes(w))) return kind;
  }
  return null;
}

