export const HOLIDAYS = {
  2026: { 설: '2026-02-17', 추석: '2026-09-25' }, 2027: { 설: '2027-02-07', 추석: '2027-09-15' },
  2028: { 설: '2028-01-27', 추석: '2028-10-03' }, 2029: { 설: '2029-02-13', 추석: '2029-09-22' },
  2030: { 설: '2030-02-03', 추석: '2030-09-12' },
};
/** 그 해·달에 든 명절 이름(설·추석) 또는 null. 연휴 사흘(앞뒤 하루)도 날짜로 돌려준다 */
export function holidayIn(year, month) {
  const h = HOLIDAYS[year];
  if (!h) return null;
  for (const [name, iso] of Object.entries(h)) {
    const d = new Date(`${iso}T00:00:00`);
    if (d.getMonth() + 1 === month) {
      const days = [-1, 0, 1].map((k) => { const x = new Date(d); x.setDate(x.getDate() + k); return `${x.getFullYear()}-${String(x.getMonth() + 1).padStart(2, '0')}-${String(x.getDate()).padStart(2, '0')}`; });
      return { name, days };
    }
  }
  return null;
}

