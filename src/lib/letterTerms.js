// 잠든 시간 글자 → 늦게 잤나(자정 이후)
export const lateNight = (t) => {
  const s = String(t || '');
  if (!s) return null;
  if (/이후|새벽/.test(s)) return true;
  const n = Number((s.match(/\d+/) || [])[0]);
  if (!Number.isFinite(n)) return null;
  if (s.startsWith('~')) return false;
  return n >= 1 && n <= 5;      // 12시는 '자정 무렵' — 자정을 넘긴 건 1시부터
};

